function make(d: Def): Exercise {
  const fedb = d.fedb?.[0]
  return {
    id: d.id,
    name: frenchSpacing(d.name),
    nameEn: d.aliases?.[0] ?? null,
    aliases: d.aliases ?? [],
    category: d.category ?? 'strength',
    level: d.level,
    mechanic: d.mechanic === undefined ? 'compound' : d.mechanic,
    force: d.force ?? null,
    primaryMuscles: d.primary,
    secondaryMuscles: d.secondary ?? [],
    equipment: d.equipment ?? [],
    instructions: d.steps.map(frenchSpacing),
    tips: (d.tips ?? []).map(frenchSpacing),
    figure: d.figure,
    frames: fedb ? [`${fedb}/0.webp`, `${fedb}/1.webp`] : [],
    measure: d.measure ?? 'reps',
    unilateral: d.unilateral ?? false,
    source: 'calitrack',
  }
}

